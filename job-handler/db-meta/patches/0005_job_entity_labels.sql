-- The `system.entities.<entity>.*` key namespace is the PLATFORM-WIDE contract
-- consumed by host entity components (EntityListTable dialogs, selection
-- labels, column headers) regardless of which module serves the meta — so the
-- namespace stays `system.entities.*` even for service-owned entities.
-- Storage stays module-owned: these rows live in `job.translations`, the job
-- service is the sole authority for labels of its own entities.
--
-- Also completes `job.jobs.*` page strings for the 5 UI languages missing
-- from 0004 (en-US, fr-FR, es-ES, de-DE, pt-PT). One row per (key, language).

